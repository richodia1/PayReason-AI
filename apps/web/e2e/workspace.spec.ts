import { test, expect } from '@playwright/test'

test('sign in, save a draft, inspect audit, cancel, and use mobile navigation', async ({ page }) => {
  const runtimeErrors: string[] = []
  page.on('pageerror', error => runtimeErrors.push(error.message))
  await page.goto('/')
  await page.getByLabel(/Username/).fill(process.env.PAYREASON_ADMIN_USERNAME || 'admin')
  await page.getByLabel(/Password/).fill(process.env.PAYREASON_ADMIN_PASSWORD || 'payreason-local-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Payment register' })).toBeVisible()
  const reference = `DEMO-${Date.now()}`
  await page.getByRole('button', { name: 'New draft', exact: true }).click()
  await page.getByLabel('Order reference').fill(reference)
  await page.getByLabel(/Amount/).fill('128.50')
  await page.getByLabel('Customer reference').fill('SANDBOX-CUSTOMER')
  await page.getByRole('button', { name: 'Save draft' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: reference, exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: reference, exact: true })).toBeVisible()
  await page.screenshot({ path: '../../.local/screenshots/payments-desktop.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: reference, exact: true }).click()
  await expect(page.getByText('Draft created', { exact: true })).toBeVisible()
  await expect(page.getByText('Not submitted', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel draft', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm cancellation', exact: true }).click()
  await expect(page.getByRole('heading', { name: reference, exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Cancelled', exact: true }).click()
  await expect(page.getByRole('button', { name: reference, exact: true })).toBeVisible()
  await page.getByRole('button', { name: reference, exact: true }).click()
  await expect(page.getByText('Draft cancelled', { exact: true })).toBeVisible()
  await page.screenshot({ path: '../../.local/screenshots/payment-detail-desktop.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Close payment details' }).click()
  await expect(page.locator('.MuiDrawer-paper')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '../../.local/screenshots/payments-mobile.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'New draft', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.screenshot({ path: '../../.local/screenshots/new-draft-mobile.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Integrations', exact: true }).click()
  await expect(page.locator('.MuiDrawer-paper')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Integrations', exact: true })).toBeVisible()
  await expect(page.getByText('Not connected', { exact: true })).toHaveCount(1)
  await expect(page.getByText('Available', { exact: true })).toHaveCount(2)
  await page.screenshot({ path: '../../.local/screenshots/integrations-mobile.png', fullPage: true, animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome to PayReason.' })).toBeVisible()
  expect(runtimeErrors).toEqual([])
})
