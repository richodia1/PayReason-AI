import { test, expect } from '@playwright/test'

test('assess a sample, review a case, query evidence, and preserve the review after reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel(/Username/).fill(process.env.PAYREASON_ADMIN_USERNAME || 'admin')
  await page.getByLabel(/Password/).fill(process.env.PAYREASON_ADMIN_PASSWORD || 'payreason-local-only')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const ref = `RISK-DEMO-${Date.now()}`
  await page.getByRole('button', { name: 'New draft', exact: true }).click()
  await page.getByLabel('Order reference').fill(ref)
  await page.getByLabel(/Amount/, { exact: false }).fill('75.25')
  await page.getByRole('button', { name: 'Save draft' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: ref, exact: true }).click()
  await page.getByLabel('Demo scenario').click()
  await page.getByRole('option', { name: 'Elevated-risk sample' }).click()
  await page.getByRole('button', { name: 'Assess sample' }).click()
  await expect(page.getByText('HIGH risk', { exact: true })).toBeVisible()
  await expect(page.getByText(/synthetic-logistic-v1/)).toBeVisible()
  await page.getByLabel('Decision', { exact: true }).click()
  await page.getByRole('option', { name: 'Block', exact: true }).click()
  await page.getByLabel('Review reason').fill('Synthetic demo reviewed: unusual velocity and new device.')
  await page.getByRole('button', { name: 'Save review' }).click()
  await expect(page.getByText('Review block', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Capture payment', exact: true })).toHaveCount(0)
  await page.locator('.MuiDrawer-paper').evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: '../../.local/screenshots/risk-desktop.png', animations: 'disabled', fullPage: true })
  await page.getByRole('button', { name: 'Close payment details' }).click()
  await page.getByRole('button', { name: 'Cases', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Case queue' })).toBeVisible()
  await expect(page.getByRole('button', { name: ref, exact: true })).toBeVisible()
  await page.screenshot({ path: '../../.local/screenshots/cases-desktop.png', animations: 'disabled', fullPage: true })
  await page.getByRole('button', { name: 'Case insights', exact: true }).click()
  await page.getByRole('button', { name: 'Query records', exact: true }).click()
  await expect(page.getByRole('button', { name: ref, exact: true })).toBeVisible()
  await page.getByLabel('Case question').fill('How many blocked cases from web this year?')
  await page.getByRole('button', { name: 'Query records', exact: true }).click()
  await expect(page.getByRole('heading', { name: /assessed cases? match/ })).toBeVisible()
  await page.screenshot({ path: '../../.local/screenshots/insights-desktop.png', animations: 'disabled', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '../../.local/screenshots/insights-mobile.png', animations: 'disabled', fullPage: true })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Cases', exact: true }).click()
  await page.getByRole('button', { name: ref, exact: true }).click()
  await expect(page.getByText('HIGH risk', { exact: true })).toBeVisible()
  await page.screenshot({ path: '../../.local/screenshots/risk-mobile.png', animations: 'disabled', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: ref, exact: true }).click()
  await expect(page.getByText('Review block', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
